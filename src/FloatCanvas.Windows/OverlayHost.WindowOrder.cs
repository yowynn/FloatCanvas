using System.ComponentModel;
using System.Runtime.InteropServices;
using static FloatCanvas.Windows.NativeMethods;

namespace FloatCanvas.Windows;

public sealed partial class OverlayHost
{
    private const uint WindowOrderMessage = 0x8005;
    private const nuint WindowOrderTimer = 0x4644;
    private WinEventProcedure? _windowOrderProcedure;
    private nint _windowOrderHook;
    private bool _windowOrderPosted, _windowOrderTimerArmed, _windowOrderFollowup;
    private bool _windowOrderStopping, _windowOrderRebuilding, _windowOrderRepairing;
    private static readonly Lazy<WindowBandProcedure?> WindowBandReader = new(() =>
    {
        nint module = GetModuleHandleW("user32.dll");
        nint address = module == 0 ? 0 : GetProcAddress(module, "GetWindowBand");
        return address == 0 ? null : Marshal.GetDelegateForFunctionPointer<WindowBandProcedure>(address);
    });

    private void StartWindowOrderMonitoring()
    {
        _windowOrderProcedure = OnWindowOrderChanged;
        // Out-of-context callbacks run on this host's pump. Include SHOW, HIDE and REORDER.
        _windowOrderHook = SetWinEventHook(0x8002, 0x8004, 0, _windowOrderProcedure, 0, 0, 0);
        if (_windowOrderHook == 0) throw new Win32Exception(Marshal.GetLastWin32Error());
    }

    private void StopWindowOrderMonitoring()
    {
        _windowOrderStopping = true;
        KillTimer(ControlHandle, WindowOrderTimer);
        _windowOrderTimerArmed = _windowOrderPosted = _windowOrderFollowup = false;
        if (_windowOrderHook != 0) { UnhookWinEvent(_windowOrderHook); _windowOrderHook = 0; }
    }

    private void OnWindowOrderChanged(nint hook, uint eventId, nint hwnd, int objectId,
        int childId, uint threadId, uint eventTime)
    {
        // Never inspect content, activate a window or propagate exceptions from a native callback.
        if (_windowOrderStopping || _disposed || hwnd == 0 || childId != 0 || objectId is not (0 or -4)) return;
        // Native z-order changes notify the desktop's client, not necessarily the moved HWND.
        // The desktop has no ordinary window PID/root identity; the later actual-order check
        // makes this signal harmless when it was generated by our own successful repair.
        if (eventId == 0x8004 && objectId == -4 && hwnd == GetDesktopWindow())
        { RequestWindowOrderCheck(); return; }
        if (GetAncestor(hwnd, 2) != hwnd ||
            GetWindowThreadProcessId(hwnd, out uint process) == 0 || process == Environment.ProcessId) return;
        RequestWindowOrderCheck();
    }

    private void RequestWindowOrderCheck()
    {
        if (_windowOrderStopping || _disposed || !IsVisible && _systemInput is null) return;
        _windowOrderFollowup = true;
        if (_windowOrderPosted) return;
        _windowOrderPosted = PostMessageW(ControlHandle, WindowOrderMessage, 0, 0);
    }

    private bool HandleWindowOrderMessage(uint message, nuint wParam)
    {
        if (message == WindowOrderMessage)
        {
            _windowOrderPosted = false;
            if (!_windowOrderStopping && !_disposed && !_captureActive && !_windowOrderRebuilding &&
                (IsVisible || _systemInput is not null) && !_windowOrderTimerArmed)
                _windowOrderTimerArmed = SetTimer(ControlHandle, WindowOrderTimer, 50, 0) != 0;
            return true;
        }
        if (message != 0x113 || wParam != WindowOrderTimer) return false;
        KillTimer(ControlHandle, WindowOrderTimer);
        _windowOrderTimerArmed = false;
        if (_windowOrderStopping || _disposed || _captureActive || _windowOrderRebuilding) return true;
        RepairWindowOrder();
        // A foreground/show notification may precede the final Shell/owner transition.
        // This is one bounded follow-up per signal batch, never a periodic topmost heartbeat.
        if (_windowOrderFollowup)
        {
            _windowOrderFollowup = false;
            _windowOrderTimerArmed = SetTimer(ControlHandle, WindowOrderTimer, 150, 0) != 0;
        }
        return true;
    }

    private void RepairWindowOrder()
    {
        if (_windowOrderRepairing || _captureActive || _windowOrderRebuilding) return;
        if (TryBeginSystemScreenshot()) return;
        if (!IsVisible) return;
        using var dpi = new ThreadDpiAwarenessScope(Capabilities);
        var rows = ReadWindowOrder();
        if (rows is null) return; // A partial chain cannot establish the actual ordering.
        var displays = _windows.Select(pair => pair.Display.Handle).ToHashSet();
        var inputs = _windows.Select(pair => pair.Input.Handle).ToHashSet();
        var visibleDisplays = rows.Where(row => displays.Contains(row.Handle)).ToArray();
        if (!visibleDisplays.Any(display => !display.Topmost || rows.Any(above =>
            above.Rank < display.Rank && above.Process != Environment.ProcessId &&
            SameRepairableBand(display, above) && Intersects(display.Bounds, above.Bounds)))) return;

        // Preserve the actual order of already visible input, WPF tools, popups and owned dialogs.
        // Hidden windows and the capture scope's off-screen/hidden carriers are never shown or moved.
        var protectedWindows = rows.Where(row => row.Process == Environment.ProcessId &&
            !displays.Contains(row.Handle) && (row.Topmost || inputs.Contains(row.Handle)) &&
            visibleDisplays.Any(display => display.Band is null || row.Band is null || display.Band == row.Band));
        var stack = protectedWindows.Concat(visibleDisplays).ToArray();
        if (stack.Length == 0 || stack.Any(row => !IsWindow(row.Handle) || !IsWindowVisible(row.Handle) ||
            GetWindowThreadProcessId(row.Handle, out uint process) == 0 || process != Environment.ProcessId)) return;
        // Repair a lost topmost flag or an ordinary-window inversion, but retain external
        // topmost peers ahead of the canvas. HWND_TOPMOST alone would leapfrog a snipping
        // overlay while restoring our own tools and displays.
        var peer = rows.LastOrDefault(row => row.Process != Environment.ProcessId && row.Topmost &&
            visibleDisplays.Any(display => row.Rank < display.Rank &&
                (display.Band is null || row.Band is null || display.Band == row.Band)));
        _windowOrderRepairing = true;
        try
        {
            nint batch = BeginDeferWindowPos(stack.Length);
            if (batch == 0) return;
            // With a peer anchor, insert top-to-bottom after it. Otherwise retain the usual
            // bottom-to-top topmost promotion. Both paths are one nonactivating native batch.
            nint after = peer.Handle;
            foreach (var row in after != 0 ? stack : stack.Reverse())
            {
                const uint flags = 0x213; // NOSIZE | NOMOVE | NOACTIVATE | NOOWNERZORDER; no SHOWWINDOW.
                batch = DeferWindowPos(batch, row.Handle, after != 0 ? after : HwndTopmost, 0, 0, 0, 0, flags);
                // A tool can close between enumeration and the batch. DeferWindowPos frees
                // the batch on failure; leave input/capture and the normal error UI untouched.
                if (batch == 0) return;
                if (after != 0) after = row.Handle;
            }
            _ = EndDeferWindowPos(batch);
        }
        finally { _windowOrderRepairing = false; }
    }

    private static bool SameRepairableBand(WindowOrderRow display, WindowOrderRow above)
    {
        // Peers such as screenshot tools may cover us; only ordinary windows are blockers.
        if (above.Topmost) return false;
        if (display.Band is { } band && above.Band is { } other) return band == other;
        // GetWindowBand is optional. Without it, do not contest an unknown higher-band topmost UI.
        return !above.Topmost;
    }

    private static bool Intersects(PixelBounds a, PixelBounds b) =>
        a.Left < b.Right && a.Right > b.Left && a.Top < b.Bottom && a.Bottom > b.Top;

    private static List<WindowOrderRow>? ReadWindowOrder()
    {
        var rows = new List<WindowOrderRow>();
        var visited = new HashSet<nint>();
        nint hwnd = GetTopWindow(0);
        int rank = 0;
        for (; hwnd != 0 && rank < 8192 && visited.Add(hwnd); rank++, hwnd = GetWindow(hwnd, 2))
        {
            if (!IsWindowVisible(hwnd) || ((long)GetWindowLongPtr(hwnd, -16) & 0x20000000) != 0 ||
                !GetWindowRect(hwnd, out var bounds) || bounds.Bounds.Width <= 0 || bounds.Bounds.Height <= 0 ||
                DwmGetWindowAttribute(hwnd, 14, out int cloak, sizeof(int)) == 0 && cloak != 0) continue;
            uint thread = GetWindowThreadProcessId(hwnd, out uint process);
            if (thread == 0) continue;
            uint? band = WindowBandReader.Value is { } query && query(hwnd, out uint value) ? value : null;
            bool topmost = ((long)GetWindowLongPtr(hwnd, GwlExStyle) & ExTopmost) != 0;
            if (GetWindowThreadProcessId(hwnd, out uint currentProcess) != thread || currentProcess != process || !IsWindow(hwnd))
                continue;
            rows.Add(new(hwnd, process, rank, topmost, bounds.Bounds, band));
        }
        return hwnd == 0 ? rows : null;
    }

    private readonly record struct WindowOrderRow(nint Handle, uint Process, int Rank,
        bool Topmost, PixelBounds Bounds, uint? Band);

    [UnmanagedFunctionPointer(CallingConvention.Winapi)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private delegate bool WindowBandProcedure(nint hwnd, out uint band);
}
